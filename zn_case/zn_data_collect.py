        x_stress_dft = x_energy_dft[1:] # Consider from index 1 because index 0 is always known as 0

        dft_energy = sorted(dft_energy)
        dft_energy = np.array(dft_energy)

        dft_stress = np.gradient(dft_energy, x_energy_dft)
        dft_stress = dft_stress[1:]
