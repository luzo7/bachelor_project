def compute_energy(plane: str):
    data = pd.read_csv(f'{plane}.csv') # CSV file generated by in.{plane} (in.basal/in.prism)
    energy = data.iloc[:, 1]

    initial_energy = np.min(energy) # Energy before separation
    final_energy = np.max(energy) # Energy after separation
    area = data.iloc[-1, 3] # Same methodology as Davide

    energy = (final_energy - initial_energy) / (2 * area) * 16.0218

    return energy

# Re-adapted Davide's code for gettin both dft- and ace-generated SFE data
def get_sfe_data(src_data: str, dft: bool = False, plane: str | None = None):
    y_values = []

    with open(src_data, 'r') as file:
        for line in file:
            if dft:
                parts = line.strip().split()
            else:
                parts = line.strip().split("SFE= ")
            
            if len(parts) == 2:
                y_values.append(float(parts[1]))

    if plane == 'prism':
        if dft:
            y_values.append(y_values[0])
            x_values = [2*x/20 for x in range(0, 10)]
            y_values = [y_values[x] for x in range(0, 10)]
        else:
            x_values = np.arange(len(y_values))
            x_values = x_values / 20
    elif plane == 'pyramidal_I' or plane == 'pyramidal_II':
        if dft:
            y_values.append(y_values[0])

            # Create the reversed x-axis for DFT data
            x_values = [x/20 for x in range(0, 20)]
            y_values = [y_values[x] for x in range(0, 20)]

            if x_values[-1] < 1.0:
                x_values.append(1.0)
                y_values.append(0.0)
            elif x_values[-1] == 1.0:
                y_values[-1] = 0.0
            else:
                f = interp1d(x_values, y_values, kind='linear')
                y_at_1 = f(1.0)
                x_values.append(1.0)
                y_values.append(0.0)
        else:
            # Generate x values (0 to N-1) scaled by 1/20
            x_values = np.arange(len(y_values)) / 20

            # Ensure value at x=1.0 is zero
            if x_values[-1] < 1.0:
                x_values = np.append(x_values, 1.0)
                y_values.append(0.0)
            elif x_values[-1] == 1.0:
                y_values[-1] = 0.0
            else:
                # If x_values goes beyond 1.0, interpolate to get y at x=1.0
                f = interp1d(x_values, y_values, kind='linear')
                y_at_1 = f(1.0)
                x_values = np.append(x_values, 1.0)
                y_values.append(0.0)  # or y_at_1 if you want a smooth continuation
    else:
        # Append the value at index 0 to the end to represent index 40
        y_values.append(y_values[0])
        
        # Create the reversed x-axis (40 becomes 0, 39 becomes 1, etc.)
        x_values = [(40 - x)/40 for x in range(24, 41)]
        
        # Extract the corresponding y values for the reversed x-axis
        y_values = [y_values[x] for x in range(24, 41)]

    return x_values, y_values

